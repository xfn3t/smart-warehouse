   FROM (((public.robots r
     JOIN public.warehouses w ON (((w.id = r.warehouse_id) AND (w.is_deleted = false))))
     JOIN public.robot_status rs ON ((rs.id = r.status_id)))
     LEFT JOIN LATERAL ( SELECT count(*) AS scan_count,
            max(ih.scanned_at) AS last_scan_at,
            count(*) FILTER (WHERE ((ist.code)::text = 'OK'::text)) AS ok_count,
            count(*) FILTER (WHERE ((ist.code)::text = 'LOW_STOCK'::text)) AS low_stock_count,
            count(*) FILTER (WHERE ((ist.code)::text = 'CRITICAL'::text)) AS critical_count,
            COALESCE(sum(ih.difference), (0)::bigint) AS total_diff
           FROM (public.inventory_history ih
             JOIN public.inventory_status ist ON ((ist.id = ih.status_id)))
          WHERE ((ih.robot_id = r.id) AND (ih.is_deleted = false))) sc ON (true))
  WHERE (r.is_deleted = false);


