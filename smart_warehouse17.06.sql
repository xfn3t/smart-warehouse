CREATE VIEW public.v_robot_activity_report AS
 SELECT r.id AS robot_id,
    r.robot_code,
    w.code AS warehouse_code,
    w.name AS warehouse_name,
    rs.code AS robot_status,
    r.battery_level,
    r.last_update,
    COALESCE(sc.scan_count, (0)::bigint) AS total_scans,
    COALESCE(sc.last_scan_at, NULL::timestamp without time zone) AS last_scan_at,
    COALESCE(sc.ok_count, (0)::bigint) AS ok_scans,
    COALESCE(sc.low_stock_count, (0)::bigint) AS low_stock_scans,
    COALESCE(sc.critical_count, (0)::bigint) AS critical_scans,
